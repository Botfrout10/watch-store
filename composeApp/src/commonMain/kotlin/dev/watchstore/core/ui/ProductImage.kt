/** Cards use 4:5 so a 2-up grid tiles without ragged bottoms. */
const val CARD_ASPECT = 4f / 5f

/** Detail hero is taller and more cinematic. */
const val HERO_ASPECT = 3f / 4f

/**
 * Product imagery.
 *
 * Renders generated artwork when the product has it, and otherwise draws a lit
 * silhouette. Two properties are deliberate:
 *
 *  1. **Every product gets its own artwork**, generated by
 *     `tools/gen-mock-images.ts`, so the catalogue reads as a curated set rather
 *     than one placeholder repeated.
 *  2. **The aspect ratio is fixed and external to this composable**, so swapping
 *     the drawn fallback for real assets causes no reflow anywhere.
 *
 * Assets live in `composeResources/drawable/` and are committed, so a fresh
 * clone always compiles and renders. Regenerate with
 * `bun run tools/gen-mock-images.ts`.
 */
@Composable
fun ProductImage(
    product: Product,
    modifier: Modifier = Modifier,
    shape: Shape = RectangleShape,
    contentScale: ContentScale = ContentScale.FillBounds,
) {
    val image = product.image
    if (image != null) {
        Image(
            painter = painterResource(image),
            contentDescription = product.name,
            contentScale = contentScale,
            modifier = modifier.clip(shape),
        )
        return
    }

    Canvas(modifier.clip(shape)) {
        drawBackdrop(product)
        when (product.kind) {
            ProductKind.WATCH -> drawWatch(product)
            ProductKind.BOX -> drawBox(product)
            ProductKind.ACCESSORY -> drawAccessory(product)
        }
    }
}

@Composable
fun ProductImageCard(
    product: Product,
    modifier: Modifier = Modifier,
    shape: Shape = RectangleShape,
) {
    ProductImage(
        product = product,
        modifier = modifier.aspectRatio(CARD_ASPECT),
        shape = shape,
    )
}

@Composable
fun ProductImageHero(
    product: Product,
    modifier: Modifier = Modifier,
    shape: Shape = RectangleShape,
) {
    // Artwork is 4:5; the hero slot is 3:4, so crop rather than squash.
    ProductImage(
        product = product,
        modifier = modifier.aspectRatio(HERO_ASPECT),
        shape = shape,
        contentScale = ContentScale.Crop,
    )
}

